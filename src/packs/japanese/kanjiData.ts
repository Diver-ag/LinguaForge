export function getKanjiBreakdown(word: string): KanjiDetail[] {
  const result: KanjiDetail[] = [];
  const seen = new Set<string>();
  for (const char of word) {
    if (/[\u4e00-\u9faf\u3400-\u4dbf]/.test(char) && !seen.has(char)) {
      seen.add(char);
      if (JAPANESE_KANJI_DATABASE[char]) {
        result.push(JAPANESE_KANJI_DATABASE[char]);
      } else {
        result.push({
          character: char,
          meanings: ['Kanji character'],
          readings: {},
          radicals: [],
        });
      }
    }
  }
  return result;
}
